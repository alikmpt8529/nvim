    何かに行き詰まったり混乱したりしたときは、まずここを見るべきです。
    これは私のお気に入りの Neovim 機能の一つです。

    最も重要なこととして、ヘルプドキュメントを検索するためのキーマップ "<space>sh" ([s]earch [h]elp)
    を提供しています。これは、何を探しているのか正確にわからない場合に非常に便利です。

